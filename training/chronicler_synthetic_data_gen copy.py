PROMPT_TEMPLATE = """
You are an AI assistant designed to generate realistic training data for keeping track of a table top role-playing game (TTRPG) campaign.
This training data will be used to train an AI assistant known as the Chronicler, which will help game masters keep track of their campaigns.
The Chronicler will take take the last player and dungeon master utterances and create scene notes based on them.
Your task is to generate examples for the Chronicler to learn from.

You will generate a player utterance and a game master utterance that could be said during a TTRPG campaign and then generate scene notes
you would expect to be created or updated based on the player and game master utterances.

########
Instructions:

Generate a player utterance that could be said during a TTRPG campaign.
Generate a game master utterance that could be said during a TTRPG campaign.
Create scene notes based on the player and game master utterances.

########
Important Notes:

Use proper names or nouns whenever possible for characters, locations, and items.
Never make assumptions or infer information that is not explicitly stated by the player or dungeom master in the scene notes.

########
Examples:
{examples}

########
The only thing returned should be returned in a json object in this format:
{format_instructions}

########
Now, generate and example game master utterance and create new scene notes based on the player and game master utterances.
"""

class SceneNotes(BaseModel):
    player_characters: List[str] = Field(
        description="List of player characters in the scene",
    )
    non_player_characters: List[str] = Field(
        description="List of non-player characters in the scene",
    )
    players_characters_location: List[str] = Field(
        description="The players location from largest to smallest (e.g. region, city, building, room)",
    )
    weather: List[str] = Field(
        description="The weather in the scene (e.g. sunny, rainy, snowy, foggy)",
    )
    time_of_day: str = Field(
        description="The time of day in the scene (e.g. morning, afternoon, evening, midnight, early morning)",
    )
    mood: List[str] = Field(
        description="The keywords that describe the mood of the scene (e.g. tense, relaxed, somber)",
    )

class ChroniclerOutput(BaseModel):
    scene_notes: SceneNotes = Field(
        description="Secene notes created or updated based on the player and game master utterances",
    )
    facts: List[str] = Field(
        description="List of independent facts extracted from the player and game master utterances. These facts must make sense without the context of the utterances, scene notes, or other facts. Facts should NEVER include minor details or transient information. Facts should be relevant to the campaign and the characters, locations, and items in it. Facts should be written in complete sentences. Each fact should have a high likelihood of being true a month from now. Each fact must include a proper name or noun for a person, place, or thing.",
    )


class ChroniclerInput(BaseModel):
    player_utterance: str = Field(
        description="Player utterance generated by the LLM",
    )
    game_master_utterance: str = Field(
        description="Game master utterance generated by the LLM",
    )

class ChroniclerTrainingEntry(BaseModel):
    chronicler_input: ChroniclerInput = Field(
        description="Input to the Chronicler",
    )
    chronicler_output: ChroniclerOutput = Field(
        description="Output from the Chronicler",
    )

