model = OllamaLLM(model="mistral:7b-instruct")

def generate_llm_output():

    try:
        parser = PydanticOutputParser(pydantic_object=ChroniclerTrainingEntry)
        prompt = PromptTemplate(
            template=PROMPT_TEMPLATE,
            input_variables=["examples"],
            partial_variables={"format_instructions": parser.get_format_instructions()},
        )

        examplesStr = ""

        for example in examples:
            examplesStr += example.model_dump_json(indent=2) + "\n"

        chain = prompt | model | parser
        response  = chain.invoke({"examples": examplesStr})

        entry = response
        print(entry.model_dump_json(indent=2))
        return entry

    except Exception as e:
        print(e)
        return []


generate_llm_output()
